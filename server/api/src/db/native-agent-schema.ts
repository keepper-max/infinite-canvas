import {
  pgTable,
  uuid,
  text,
  integer,
  timestamp,
  jsonb,
  bigint,
  bigserial,
  boolean,
} from "drizzle-orm/pg-core";
// SQL owns FK/check/partial indexes, as in knowledge-schema.
const id = () => uuid("id").defaultRandom().primaryKey();
const created = () =>
  timestamp("created_at", { withTimezone: true }).defaultNow();
const updated = () =>
  timestamp("updated_at", { withTimezone: true }).defaultNow();
export const nativeAgentSessions = pgTable("native_agent_sessions", {
  id: id(),
  actorId: uuid("actor_id").notNull(),
  projectId: uuid("project_id").notNull(),
  operationId: uuid("operation_id").notNull(),
  title: text("title").notNull(),
  mode: text("mode").notNull(),
  protocolVersion: integer("protocol_version").notNull(),
  messageSchemaVersion: integer("message_schema_version").notNull(),
  closedAt: timestamp("closed_at", { withTimezone: true }),
  createdAt: created(),
  updatedAt: updated(),
});
